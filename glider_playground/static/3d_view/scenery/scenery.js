// Scenery for the 3D view: decorative low-poly life scattered over the
// bathymetry and through the water column (kelp, seagrass, coral, fish,
// jellyfish, whales, trees, bushes). Purely cosmetic — nothing here touches
// the science. Behind the "Scenery" style toggle in 3d_view.html.
//
// Placement is rule-based (RULES below): each kind lists where it's plausible
// (seabed depth band / land / floating depth band) and a latitude band, plus
// a target density. Instances are drawn from a seeded RNG so the same file
// always gets the same scene. Everything is merged into ONE flat-shaded
// mesh3d (same look as the vehicles); underwater things sway or drift a
// little during playback via sway().
//
// Models: ./<name>.json, generated by ./make_models.py (metres, +z up;
// origin at ground level for things that stand, at body centre for things
// that float).
window.Scenery = (() => {
    const MODEL_URL = name => `/static/3d_view/scenery/${name}.json`;

    // Exactly one of:
    //   depth: [min, max] seabed depth (m, positive down) — stands on the seabed
    //   land: true — stands on land (bathy > 0)
    //   float: [min, max] depth (m) — hangs in the water column (needs water below)
    // lat: |latitude| band. size: on-screen height in scene units (the
    // scene is ~1 unit across; the glider is drawn 0.03 long).
    // density: fraction of eligible bathy cells that get one; max: hard cap.
    // sway: underwater motion strength (0 = rigid): plants bend from the base.
    // swim: { r, period, bob } — floating kinds cruise a fixed elliptical loop
    //   of radius ~r (scene units) around their spawn point once per `period`
    //   seconds, nose along the path; `bob` adds a vertical wobble (fraction
    //   of size). Stateless: position is a pure function of the clock.
    // snow: what to do where the view paints the land white (see snowAt):
    //   'coat' blends the colours towards snow, 'skip' places nothing.
    // Floating kinds come from the species lists below via small factories so
    // the per-species line is just: model, real length (m), |lat| band, depth
    // band (m), and any override. On-screen size scales with real length
    // (whales are big, anchovies are small) — same cartoon scale as the glider.
    const M_PER_UNIT = 0.0043;    // scene units per metre of animal (14 m humpback → 0.06)
    // `group` caps the total across species (GROUP_MAX) so a subpolar scene
    // doesn't get every whale at once; species order is shuffled per file.
    const whale  = (model, L, lat, float, o = {}) => ({ model, group: 'whale', lat, float, size: L * M_PER_UNIT, density: 0.01, max: 1, swim: { r: 0.25, period: 120, bob: 0.1 }, ...o });
    const shark  = (model, L, lat, float, o = {}) => ({ model, group: 'shark', lat, float, size: L * M_PER_UNIT, density: 0.01, max: 2, swim: { r: 0.15, period: 70, bob: 0.1 }, ...o });
    const school = (model, lat, float, o = {}) => ({ model, group: 'school', lat, float, size: 0.02, density: 0.05, max: 25, swim: { r: 0.08, period: 45, bob: 0.2 }, ...o });
    const jelly  = (model, lat, float, o = {}) => ({ model, group: 'jelly', lat, float, size: 0.008, density: 0.05, max: 25, swim: { r: 0.01, period: 50, bob: 0.6 }, ...o });
    const GROUP_MAX = { whale: 4, shark: 3, school: 40, jelly: 40 };

    const RULES = [
        // ── Standing things ──
        // Kelp forests: rocky temperate-to-subpolar coasts, photic zone; absent from the tropics.
        { model: 'kelp',     depth: [2, 30],  lat: [28, 72], size: 0.020, density: 0.6, max: 90,  sway: 1.0 },
        // Seagrass meadows: sheltered shallows from the tropics to the sub-Arctic.
        { model: 'seagrass', depth: [1, 15],  lat: [0, 65],  size: 0.008, density: 0.6, max: 90,  sway: 0.6 },
        // Cold-water coral (Lophelia-type reefs): deep temperate/subpolar seabed, no sunlight needed.
        { model: 'coral',    depth: [150, 1200], lat: [40, 72], size: 0.010, density: 0.3, max: 80 },
        // Palms: tropical / subtropical shores.
        { model: 'palm',     land: true,      lat: [0, 28],  size: 0.020, density: 0.4, max: 60 },
        // Conifers: temperate and boreal land up to the Arctic treeline; snow-covered where the land is drawn white.
        { model: 'conifer',  land: true,      lat: [28, 70], size: 0.025, density: 0.4, max: 60, snow: 'coat' },
        // Shrubs: any land up to the tundra shrub line, but not on snow.
        { model: 'bush',     land: true,      lat: [0, 68],  size: 0.008, density: 0.5, max: 120, snow: 'skip' },

        // ── Whales & dolphins (model, length m, |lat|, depth m) ──
        whale('whale_humpback', 14, [0, 75],  [3, 60]),
        whale('whale_minke',     8, [30, 80], [3, 60],  { max: 2 }),
        whale('whale_fin',      20, [20, 75], [5, 100]),
        whale('whale_sei',      15, [20, 65], [5, 100]),
        whale('whale_blue',     25, [0, 70],  [5, 100], { density: 0.005 }),
        whale('whale_sperm',    16, [0, 70],  [50, 800], { swim: { r: 0.2, period: 150, bob: 0.3 } }),
        whale('whale_orca',      7, [0, 80],  [3, 50],  { max: 3, swim: { r: 0.2, period: 60, bob: 0.15 } }),
        whale('whale_pilot',     6, [20, 65], [10, 300], { max: 3 }),
        whale('whale_beluga',  4.5, [60, 82], [2, 40],  { max: 3 }),
        whale('whale_narwhal', 4.5, [65, 85], [5, 300], { max: 2 }),
        whale('dolphin_common', 2.3, [0, 60], [1, 30],  { max: 4, density: 0.02, swim: { r: 0.15, period: 40, bob: 0.3 } }),

        // ── Sharks ──
        shark('shark_basking',    8, [30, 65], [5, 200], { max: 1 }),
        shark('shark_white',      5, [0, 60],  [5, 200], { max: 1 }),
        shark('shark_blue',       3, [0, 60],  [10, 300]),
        shark('shark_porbeagle',  2.5, [30, 70], [10, 300]),
        shark('shark_hammerhead', 3.5, [0, 40], [5, 150]),
        shark('shark_greenland',  4, [55, 82], [200, 1200], { swim: { r: 0.1, period: 180, bob: 0.05 } }),

        // ── Schooling fish ──
        school('fish_herring',    [30, 75], [20, 200]),
        school('fish_mackerel',   [25, 70], [10, 150]),
        school('fish_capelin',    [55, 80], [20, 200]),
        school('fish_cod',        [40, 75], [50, 300],  { size: 0.025, max: 10 }),
        school('fish_sardine',    [0, 50],  [10, 100]),
        school('fish_anchovy',    [0, 50],  [5, 80]),
        school('fish_tuna',       [0, 50],  [20, 300],  { size: 0.035, max: 6, swim: { r: 0.15, period: 35, bob: 0.2 } }),
        school('fish_lanternfish', [0, 70], [300, 1000], { size: 0.012, max: 30 }),

        // ── Jellyfish ──
        jelly('jelly_moon',      [0, 70],  [1, 50]),
        jelly('jelly_lionsmane', [40, 80], [5, 100],  { size: 0.016, max: 10 }),
        jelly('jelly_compass',   [20, 60], [2, 40]),
        jelly('jelly_barrel',    [30, 60], [2, 40],   { size: 0.012, max: 10 }),
        jelly('jelly_blue',      [30, 65], [2, 30]),
    ];
    const SNOW_COLOUR = '#e9eef2';  // the view's snowGradientEnd
    const SIZE_JITTER = 0.25;       // ±fraction of `size`
    const SWAY_AMP = 0.12;        // fraction of a plant's height at the tip
    const SWAY_PERIOD_S = 6;      // seconds per sway cycle (wall clock)

    // Tallest thing that can stand on land (scene units): the view adds this
    // much headroom above the highest ground so nothing is clipped.
    const maxHeight = () => Math.max(0, ...RULES.filter(r => r.land).map(r => r.size * (1 + SIZE_JITTER)));

    const hexToRgb = hex => { const n = parseInt(hex.slice(1), 16); return [n >> 16, (n >> 8) & 255, n & 255]; };
    const lerpHex = (a, b, t) => { const A = hexToRgb(a), B = hexToRgb(b); return '#' + A.map((v, q) => Math.round(v + (B[q] - v) * t).toString(16).padStart(2, '0')).join(''); };

    let models = null;            // name -> merged model (from the view's loadModel)
    let state = null;             // last built geometry, for sway()

    // Small seeded RNG (mulberry32) so placement is stable across re-renders.
    function rng(seedStr) {
        let h = 1779033703;
        for (let q = 0; q < seedStr.length; q++) h = Math.imul(h ^ seedStr.charCodeAt(q), 3432918353), h = (h << 13) | (h >>> 19);
        let a = h >>> 0;
        return () => { a += 0x6D2B79F5; let t = Math.imul(a ^ (a >>> 15), 1 | a); t ^= t + Math.imul(t ^ (t >>> 7), 61 | t); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
    }

    // Load every model once; `loadModel(url)` is the view's own loader so the
    // meshes are merged exactly like the vehicles. Missing files just mean
    // that kind is skipped.
    function load(loadModel) {
        const names = [...new Set(RULES.map(r => r.model))];
        return Promise.all(names.map(n => loadModel(MODEL_URL(n)).catch(() => null)))
            .then(ms => { models = {}; names.forEach((n, q) => { if (ms[q]) models[n] = ms[q]; }); return models; });
    }

    // Bilinear seabed/land height (display units) at lon/lat from the grid.
    function heightAt(bx, by, bz, lon, lat) {
        const fx = (lon - bx[0]) / (bx[bx.length - 1] - bx[0]) * (bx.length - 1);
        const fy = (lat - by[0]) / (by[by.length - 1] - by[0]) * (by.length - 1);
        const x0 = Math.max(0, Math.min(bx.length - 2, Math.floor(fx))), y0 = Math.max(0, Math.min(by.length - 2, Math.floor(fy)));
        const tx = Math.max(0, Math.min(1, fx - x0)), ty = Math.max(0, Math.min(1, fy - y0));
        const z00 = bz[y0][x0], z01 = bz[y0][x0 + 1], z10 = bz[y0 + 1][x0], z11 = bz[y0 + 1][x0 + 1];
        return (z00 * (1 - tx) + z01 * tx) * (1 - ty) + (z10 * (1 - tx) + z11 * tx) * ty;
    }

    // Build the merged scenery mesh for the current scene.
    //   data: the /api/3d_data payload (bathy_lon/lat used as the grid)
    //   bathyZ: the displayed bathymetry heights (land already scaled), or
    //     null when the seafloor is out of the focus range (then only
    //     floating kinds are placed, above floorZ)
    //   S: sceneScale {kx, ky, kz} — data units per scene unit
    //   seed: any string (the file id)
    //   snowAt: lat → 0..1 snow fraction of the drawn land (optional)
    //   floorZ: bottom of the drawn box (data units, negative)
    // Returns a mesh3d trace, or null when there's nothing to place.
    function build(data, bathyZ, S, seed, snowAt, floorZ) {
        state = null;
        if (!models) return null;
        const zAt = (lon, lat) => bathyZ ? heightAt(bx, by, bathyZ, lon, lat) : floorZ;
        const bx = data.bathy_lon, by = data.bathy_lat, nx = bx.length, ny = by.length;
        if (nx < 2 || ny < 2) return null;
        const rand = rng(seed || '');
        const out = { x: [], y: [], z: [], i: [], j: [], k: [], cell: [] };
        const sway = { x: [], y: [], ph: [] };   // per-vertex sway offsets (data units) + phase
        const movers = [];                       // swimming instances, re-posed each frame (see pose())
        const colors = [];
        const colorIdx = col => { if (!colors.includes(col)) colors.push(col); return colors.indexOf(col); };
        const lon0 = bx[0], lon1 = bx[nx - 1], lat0 = by[0], lat1 = by[ny - 1];

        // Species in a per-file random order, so group caps pick different animals each deployment.
        const order = RULES.slice();
        for (let q = order.length - 1; q > 0; q--) { const r = Math.floor(rand() * (q + 1)); [order[q], order[r]] = [order[r], order[q]]; }
        const groupCount = {};
        for (const rule of order) {
            const M = models[rule.model];
            if (!M || (!bathyZ && !rule.float)) continue;   // nothing to stand on
            if (rule.group && (groupCount[rule.group] || 0) >= GROUP_MAX[rule.group]) continue;
            const zSpan = (Math.max(...M.z) - Math.min(...M.z)) / M.length;   // vertical extent per unit of `size` (1 for upright things)
            // Eligible cells (cell centres; the instance is jittered within the cell).
            const cells = [];
            for (let iy = 0; iy < ny; iy++) {
                const alat = Math.abs(by[iy]);
                if (alat < rule.lat[0] || alat > rule.lat[1]) continue;
                for (let ix = 0; ix < nx; ix++) {
                    const z = bathyZ ? bathyZ[iy][ix] : floorZ;
                    if (z == null || !isFinite(z)) continue;
                    const ok = rule.land ? z > 0 : rule.float ? -z > rule.float[0] : (-z >= rule.depth[0] && -z <= rule.depth[1]);
                    if (ok) cells.push(iy * nx + ix);
                }
            }
            let want = Math.min(rule.max, Math.round(cells.length * rule.density));
            if (rule.group) want = Math.min(want, GROUP_MAX[rule.group] - (groupCount[rule.group] || 0));
            for (let q = 0; q < want; q++) {
                // Partial Fisher-Yates: pick without replacement.
                const pick = q + Math.floor(rand() * (cells.length - q));
                [cells[q], cells[pick]] = [cells[pick], cells[q]];
                const iy = Math.floor(cells[q] / nx), ix = cells[q] % nx;
                const dlon = bx[Math.min(nx - 1, ix + 1)] - bx[Math.max(0, ix - 1)], dlat = by[Math.min(ny - 1, iy + 1)] - by[Math.max(0, iy - 1)];
                const lon = bx[ix] + (rand() - 0.5) * dlon * 0.5, lat = by[iy] + (rand() - 0.5) * dlat * 0.5;
                const ground = zAt(lon, lat);
                if (rule.land ? ground <= 0 : ground >= 0) continue;   // jitter slid it off the eligible patch
                const snow = rule.land && snowAt ? snowAt(lat) : 0;
                if (rule.snow === 'skip' && snow > 0.5) continue;

                // On-screen height, ± variety; underwater things never poke through the surface.
                let h = rule.size * (1 + (rand() * 2 - 1) * SIZE_JITTER);
                if (!rule.land) h = Math.min(h, 0.85 * (-ground) / (zSpan * S.kz));
                // Anchor height: the ground for things that stand; a random
                // depth in the band (clear of both surface and seabed) for floaters.
                let anchor = ground;
                if (rule.float) {
                    const half = (h * zSpan * 0.5 + (rule.swim ? rule.swim.bob * h * 0.5 : 0)) * S.kz;
                    const dMin = Math.max(rule.float[0], half), dMax = Math.min(rule.float[1], -ground - half);
                    if (dMax <= dMin) continue;
                    anchor = -(dMin + rand() * (dMax - dMin));
                }
                // Keep the whole footprint inside the box: the axis range slices
                // any mesh crossing it open. Footprint ≈ half the height each way.
                const reach = h * 0.5 + (rule.swim ? rule.swim.r * 1.3 : 0);   // furthest the mesh gets from the spawn point
                const padX = reach * S.kx, padY = reach * S.ky;
                if (lon - padX < lon0 || lon + padX > lon1 || lat - padY < lat0 || lat + padY > lat1) continue;
                const k = h / M.length, phase = rand() * 2 * Math.PI;
                let c = [lon / S.kx, lat / S.ky, anchor / S.kz], cy, sy;
                const base = out.x.length;
                if (rule.swim) {
                    const sw = rule.swim;
                    const mv = { base, n: M.x.length, k, M, c, rx: sw.r * (0.7 + rand() * 0.6), ry: sw.r * (0.7 + rand() * 0.6),
                                 w: 2 * Math.PI / sw.period * (rand() < 0.5 ? 1 : -1), phase, bob: sw.bob * h };
                    movers.push(mv);
                    ({ c, cy, sy } = pose(mv, 0));
                } else {
                    const yaw = rand() * 2 * Math.PI; cy = Math.cos(yaw); sy = Math.sin(yaw);
                }
                const swayDir = rand() * 2 * Math.PI;
                const amp = (rule.sway || 0) * SWAY_AMP * h;
                for (let v = 0; v < M.x.length; v++) {
                    const mx = M.x[v] * k, my = M.y[v] * k, mz = M.z[v] * k;
                    out.x.push((c[0] + mx * cy - my * sy) * S.kx);
                    out.y.push((c[1] + mx * sy + my * cy) * S.ky);
                    out.z.push((c[2] + mz) * S.kz);
                    const w = amp * (mz / h);   // plants bend toward the tip
                    sway.x.push(w * Math.cos(swayDir) * S.kx); sway.y.push(w * Math.sin(swayDir) * S.ky); sway.ph.push(phase);
                }
                out.i.push(...M.i.map(v => v + base)); out.j.push(...M.j.map(v => v + base)); out.k.push(...M.k.map(v => v + base));
                const coat = rule.snow === 'coat' ? 0.8 * snow : 0;
                const map = M.colorscale.map(([, col]) => colorIdx(coat ? lerpHex(col, SNOW_COLOUR, coat) : col));
                out.cell.push(...M.cell.map(ci => map[ci]));
                if (rule.group) groupCount[rule.group] = (groupCount[rule.group] || 0) + 1;
            }
        }
        if (!out.x.length) return null;
        state = { x: out.x, y: out.y, z: out.z, sway, movers, S, moving: movers.length > 0 || sway.x.some(v => v !== 0) };
        const cmax = Math.max(colors.length - 1, 1);
        return {
            type: 'mesh3d', x: out.x, y: out.y, z: out.z, i: out.i, j: out.j, k: out.k,
            intensity: out.cell, intensitymode: 'cell', cmin: 0, cmax,
            colorscale: colors.length === 1 ? [[0, colors[0]], [1, colors[0]]] : colors.map((col, q) => [q / cmax, col]),
            showscale: false, flatshading: true,
            lighting: { ambient: 0.55, diffuse: 0.7, specular: 0.1, roughness: 0.8 },
            name: 'Scenery', hoverinfo: 'skip'
        };
    }

    // Where a swimmer is at time t: centre (scene units) on its ellipse,
    // plus the yaw (cos/sin) that points its nose along the path.
    function pose(mv, t) {
        const a = mv.w * t + mv.phase;
        const c = [mv.c[0] + mv.rx * Math.cos(a), mv.c[1] + mv.ry * Math.sin(a), mv.c[2] + mv.bob * 0.5 * Math.sin(2 * a + 1)];
        const vx = -mv.rx * Math.sin(a) * mv.w, vy = mv.ry * Math.cos(a) * mv.w, vl = Math.hypot(vx, vy) || 1;
        return { c, cy: vx / vl, sy: vy / vl };
    }

    // Animated copy of the last built geometry at wall-clock time `tSec`
    // (plants sway, swimmers move along their loops), or null when nothing
    // moves. Arrays are fresh each call, ready for fastXYZ.
    function sway(tSec) {
        if (!state || !state.moving) return null;
        const { x, y, z, sway: s, movers, S } = state, n = x.length, w = 2 * Math.PI / SWAY_PERIOD_S;
        const xs = new Array(n), ys = new Array(n), zs = z.slice();
        for (let q = 0; q < n; q++) { const f = Math.sin(w * tSec + s.ph[q]); xs[q] = x[q] + s.x[q] * f; ys[q] = y[q] + s.y[q] * f; }
        for (const mv of movers) {
            const { c, cy, sy } = pose(mv, tSec), M = mv.M, k = mv.k;
            for (let v = 0; v < mv.n; v++) {
                const mx = M.x[v] * k, my = M.y[v] * k, q = mv.base + v;
                xs[q] = (c[0] + mx * cy - my * sy) * S.kx;
                ys[q] = (c[1] + mx * sy + my * cy) * S.ky;
                zs[q] = (c[2] + M.z[v] * k) * S.kz;
            }
        }
        return { x: xs, y: ys, z: zs };
    }

    return { load, build, sway, maxHeight, RULES };
})();
